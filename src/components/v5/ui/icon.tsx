export function V5Icon({
  name,
  className,
  ...props
}: React.HTMLAttributes<HTMLSpanElement> & { name: string }) {
  const Icon = iconMap[name] ?? Cloud;
  return (
    <span
      aria-hidden="true"
      className={cn("inline-flex shrink-0 items-center justify-center leading-none", className)}
      {...props}
    >
      <Icon size="1em" strokeWidth={1.9} />
    </span>
  );
}

