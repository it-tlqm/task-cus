export function V5Icon({
  name,
  className,
  title,
}: {
  name: string;
  className?: string;
  title?: string;
}) {
  const Icon = ICON_MAP[name] ?? Circle;
  const match = className?.match(/text-\[(\d+)px\]/);
  const size = match ? Number(match[1]) : 18;
  return (
    <Icon
      size={size}
      strokeWidth={1.8}
      className={className}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    />
  );
}
